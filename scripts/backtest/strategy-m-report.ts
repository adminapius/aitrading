import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'

/**
 * Builds docs/strategy-m-backtest.md from the JSON written by strategy-m.ts.
 * Usage: pnpm exec tsx scripts/backtest/strategy-m-report.ts --design=<design.json> --holdout=<holdout.json>
 */

type Summary = { trades: number; winRate: number; avgR: number; profitFactor: number; pnl: number; maxDrawdownPct: number }
type Run = { id: string; label: string; summary: Summary; byMonth: Record<string, { trades: number; pnl: number }> }
type PeriodResult = { feed: string; period: string; tradingDays: number; poolSymbolsFetched: number; runs: Run[] }

const args = new Map<string, string>()
for (const arg of process.argv.slice(2)) {
  const [key, value] = arg.replace(/^--/, '').split('=')
  args.set(key, value ?? 'true')
}

const STARTING_EQUITY = 2000
const PASS = { minProfitFactor: 1.3, minTrades: 40, maxDrawdownPct: 10, maxDegradation: 0.25 }

function load(path: string | undefined): PeriodResult {
  if (!path) throw new Error('missing --design or --holdout path')
  return JSON.parse(readFileSync(resolve(process.cwd(), path), 'utf8')) as PeriodResult
}

const design = load(args.get('design'))
const holdout = load(args.get('holdout'))
const outPath = resolve(process.cwd(), args.get('out') ?? 'docs/strategy-m-backtest.md')

const money = (v: number) => `${v < 0 ? '-' : ''}$${Math.abs(v).toFixed(2)}`
const pf = (v: number) => (Number.isFinite(v) ? v.toFixed(2) : 'inf')

function summaryTable(result: PeriodResult) {
  const rows = result.runs.map((run) => {
    const s = run.summary
    return `| ${run.id} | ${s.trades} | ${s.winRate.toFixed(1)}% | ${s.avgR.toFixed(3)} | ${pf(s.profitFactor)} | ${s.maxDrawdownPct.toFixed(1)}% | ${money(s.pnl)} | ${money(STARTING_EQUITY + s.pnl)} |`
  })
  return [
    '| Variant | Trades | Win rate | Avg R | Profit factor | Max DD | P&L | Ending equity |',
    '|---|---:|---:|---:|---:|---:|---:|---:|',
    ...rows,
  ].join('\n')
}

function monthTable(result: PeriodResult) {
  const months = [...new Set(result.runs.flatMap((run) => Object.keys(run.byMonth)))].sort()
  const header = `| Month | ${result.runs.map((run) => run.id).join(' | ')} |`
  const sep = `|---|${result.runs.map(() => '---:').join('|')}|`
  const rows = months.map((month) => {
    const cells = result.runs.map((run) => {
      const m = run.byMonth[month]
      return m ? `${money(m.pnl)} (${m.trades})` : '-'
    })
    return `| ${month} | ${cells.join(' | ')} |`
  })
  return [header, sep, ...rows].join('\n')
}

function verdict(id: string) {
  const h = holdout.runs.find((run) => run.id === id)?.summary
  const d = design.runs.find((run) => run.id === id)?.summary
  if (!h || !d) return { id, pass: false, reasons: ['missing period result'] }
  const reasons: string[] = []
  if (!(h.profitFactor >= PASS.minProfitFactor)) reasons.push(`holdout PF ${pf(h.profitFactor)} < ${PASS.minProfitFactor}`)
  if (h.trades < PASS.minTrades) reasons.push(`holdout trades ${h.trades} < ${PASS.minTrades}`)
  if (!(h.avgR > 0)) reasons.push(`holdout avg R ${h.avgR.toFixed(3)} <= 0`)
  if (!(h.maxDrawdownPct < PASS.maxDrawdownPct)) reasons.push(`holdout max DD ${h.maxDrawdownPct.toFixed(1)}% >= ${PASS.maxDrawdownPct}%`)
  if (d.profitFactor > 0 && h.profitFactor < d.profitFactor * (1 - PASS.maxDegradation)) {
    reasons.push(`holdout PF ${pf(h.profitFactor)} is more than ${PASS.maxDegradation * 100}% below design PF ${pf(d.profitFactor)}`)
  }
  return { id, pass: reasons.length === 0, reasons }
}

const verdicts = holdout.runs.map((run) => verdict(run.id))

const report = `# Strategy M (Midday) backtest

Generated by \`scripts/backtest/strategy-m.ts\` + \`scripts/backtest/strategy-m-report.ts\`.

- Market data: Alpaca **${holdout.feed.toUpperCase()}** 1-min bars and quotes (no IEX).
- Entry window 11:00-15:30 ET, all positions flattened at 15:55 ET.
- Fills: buy at ask + slippage, sell at bid; no fills during LULD halts; gapped stops fill at the next real trade.
- Pretend account: ${money(STARTING_EQUITY)} per variant, compounded.
- \`M-all-x2\` / \`M-all-x3\` are stress runs of the combined variant with 2x / 3x slippage.

## Pass rule

Holdout profit factor >= ${PASS.minProfitFactor}, at least ${PASS.minTrades} holdout trades, holdout average R > 0, holdout max drawdown < ${PASS.maxDrawdownPct}%, and holdout profit factor not more than ${PASS.maxDegradation * 100}% below design.

| Variant | Result | Reasons |
|---|---|---|
${verdicts.map((v) => `| ${v.id} | ${v.pass ? 'PASS' : 'FAIL'} | ${v.reasons.join('; ') || '-'} |`).join('\n')}

## Holdout ${holdout.period === 'holdout' ? '(2025-04-01 to 2025-09-30, not tuned on)' : ''}

Trading days: ${holdout.tradingDays}. Symbols fetched: ${holdout.poolSymbolsFetched}.

${summaryTable(holdout)}

### Holdout by month - P&L (trades)

${monthTable(holdout)}

## Design (2025-10-01 to 2026-10-07)

Trading days: ${design.tradingDays}. Symbols fetched: ${design.poolSymbolsFetched}.

${summaryTable(design)}

### Design by month - P&L (trades)

${monthTable(design)}
`

mkdirSync(dirname(outPath), { recursive: true })
writeFileSync(outPath, report)
console.log(`[strategy-m-report] wrote ${outPath}`)
console.log(verdicts.map((v) => `${v.id}: ${v.pass ? 'PASS' : 'FAIL'}`).join('\n'))
